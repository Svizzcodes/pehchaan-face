export function formatNumber(num: number | string, language: LanguageCode): string {
  const numStr = num.toString();
  const digits = LOCAL_DIGITS[language];
  if (!digits) return numStr;
  return numStr
    .split('')
    .map((char) => {
      const val = parseInt(char, 10);
      if (!isNaN(val) && val >= 0 && val <= 9) {
        return digits[val];
      }
      return char;
    })
    .join('');
}

